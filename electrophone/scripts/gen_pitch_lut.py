import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "pitch_lut.vhd"


def main() -> None:
    factors = [
        round(16384.0 * (2.0 ** (cents / 1200.0)))
        for cents in range(-250, 251)
    ]
    rows = []
    for start in range(0, len(factors), 10):
        values = ", ".join(f'x"{value:04X}"' for value in factors[start:start + 10])
        suffix = "," if start + 10 < len(factors) else ""
        rows.append(f"        {values}{suffix}")

    content = f"""library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- Generated by scripts/gen_pitch_lut.py.
-- Q14 phase-increment multiplier for -250..+250 cents.
package pitch_lut is
    type factor_table_t is array (0 to 500) of unsigned(15 downto 0);
    constant PITCH_FACTORS : factor_table_t := (
{chr(10).join(rows)}
    );

    function pitch_factor(cents : integer) return unsigned;
end package;

package body pitch_lut is
    function pitch_factor(cents : integer) return unsigned is
        variable index_v : integer;
    begin
        if cents < -250 then
            index_v := 0;
        elsif cents > 250 then
            index_v := 500;
        else
            index_v := cents + 250;
        end if;
        return PITCH_FACTORS(index_v);
    end function;
end package body;
"""
    OUT.write_text(content, encoding="utf-8")
    print(f"generated {len(factors)} pitch factors")


if __name__ == "__main__":
    main()
