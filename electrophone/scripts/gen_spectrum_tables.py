import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "spectrum_tables.vhd"
FFT_SIZE = 2048
LOG_SIZE = 11


def q15(value: float) -> int:
    return round(max(-1.0, min(1.0, value)) * 32767)


def values_table(values: list[int], indent: str = "        ") -> str:
    lines = []
    for start in range(0, len(values), 8):
        row = values[start : start + 8]
        lines.append(indent + ", ".join(f"to_signed({value}, 16)" for value in row))
    return ",\n".join(lines)


def main() -> None:
    hann = [
        q15(0.5 - 0.5 * math.cos(2.0 * math.pi * n / (FFT_SIZE - 1)))
        for n in range(FFT_SIZE)
    ]
    twiddle_count = FFT_SIZE // 2
    cos_table = [
        q15(math.cos(2.0 * math.pi * k / FFT_SIZE))
        for k in range(twiddle_count)
    ]
    sin_table = [
        q15(math.sin(2.0 * math.pi * k / FFT_SIZE))
        for k in range(twiddle_count)
    ]

    content = f"""library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- Generated by scripts/gen_spectrum_tables.py.
package spectrum_tables is
    constant SPECTRUM_FFT_SIZE : positive := {FFT_SIZE};
    constant SPECTRUM_LOG_SIZE : natural := {LOG_SIZE};
    type spectrum_coeff_array_t is array (natural range <>) of signed(15 downto 0);

    constant HANN_TABLE : spectrum_coeff_array_t(0 to {FFT_SIZE - 1}) := (
{values_table(hann)}
    );
    constant TWIDDLE_COS : spectrum_coeff_array_t(0 to {twiddle_count - 1}) := (
{values_table(cos_table)}
    );
    constant TWIDDLE_SIN : spectrum_coeff_array_t(0 to {twiddle_count - 1}) := (
{values_table(sin_table)}
    );

    function bit_reverse_11(value : natural) return natural;
end package;

package body spectrum_tables is
    function bit_reverse_11(value : natural) return natural is
        variable input : unsigned(10 downto 0);
        variable result : unsigned(10 downto 0) := (others => '0');
    begin
        input := to_unsigned(value, 11);
        for bit_index in 0 to 10 loop
            result(10-bit_index) := input(bit_index);
        end loop;
        return to_integer(result);
    end function;
end package body;
"""
    OUT.write_text(content, encoding="utf-8")
    print(f"generated {FFT_SIZE} Hann values and {twiddle_count} twiddles")


if __name__ == "__main__":
    main()
